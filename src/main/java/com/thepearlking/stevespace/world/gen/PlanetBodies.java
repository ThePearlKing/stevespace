import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.function.Supplier;

/**
 * Directory of the bodies whose surface is generated by {@link PlanetChunkGenerator}. Earth is not
 * here: it uses Minecraft's own generator with planet-scale inputs (see world.gen.earth). Every
 * world is the same in every save (fixed seeds); only the caves follow the world seed.
 */
public final class PlanetBodies {

    /** One world: its terrain (pure and thread-safe, shared), block builder and how cavey it is. */
    private record Entry(PlanetTerrain terrain, Supplier<ColumnBuilder> columns, double caves, List<? extends SurfaceBiome> biomes) {
    }

    private static final Map<String, Entry> WORLDS = new LinkedHashMap<>();

    static {
        MoonTerrain moon = new MoonTerrain();
        add("moon", moon, MoonColumns::new, 0.12, List.of(MoonTerrain.Biome.values()));
        MarsTerrain mars = new MarsTerrain();
        add("mars", mars, MarsColumns::new, 0.25, List.of(MarsTerrain.Biome.values()));
        VenusTerrain venus = new VenusTerrain();
        add("venus", venus, VenusColumns::new, 0.1, List.of(VenusTerrain.Biome.values()));
        add("mercury", new MercuryTerrain(), MercuryColumns::new, 0.15);
        add("io", new IoTerrain(), IoColumns::new, 0.15);
        add("europa", new EuropaTerrain(), EuropaColumns::new, 0.05);
        add("ganymede", new GanymedeTerrain(), GanymedeColumns::new, 0.15);
        add("callisto", new CallistoTerrain(), CallistoColumns::new, 0.15);
        add("titan", new TitanTerrain(), TitanColumns::new, 0.1);
        add("enceladus", new EnceladusTerrain(), EnceladusColumns::new, 0.1);
        add("triton", new TritonTerrain(), TritonColumns::new, 0.12);
        add("pluto", new PlutoTerrain(), PlutoColumns::new, 0.12);
        add("charon", new com.thepearlking.stevespace.world.planet.worlds.CharonTerrain(),
                com.thepearlking.stevespace.world.gen.worlds.CharonColumns::new, 0.1);
        add("makemake", new com.thepearlking.stevespace.world.planet.worlds.MakemakeTerrain(),
                com.thepearlking.stevespace.world.gen.worlds.MakemakeColumns::new, 0.1);
        add("eris", new com.thepearlking.stevespace.world.planet.worlds.ErisTerrain(),
                com.thepearlking.stevespace.world.gen.worlds.ErisColumns::new, 0.1);
        add("haumea", new com.thepearlking.stevespace.world.planet.worlds.HaumeaTerrain(),
                com.thepearlking.stevespace.world.gen.worlds.HaumeaColumns::new, 0.12);
        add("acheron", new com.thepearlking.stevespace.world.planet.worlds.AcheronTerrain(),
                com.thepearlking.stevespace.world.gen.worlds.AcheronColumns::new, 0.0);
        // The main belt's big four.
        addAsteroid("ceres", com.thepearlking.stevespace.world.planet.worlds.AsteroidTerrain.Kind.CERES, 470);
        addAsteroid("vesta", com.thepearlking.stevespace.world.planet.worlds.AsteroidTerrain.Kind.VESTA, 263);
        addAsteroid("pallas", com.thepearlking.stevespace.world.planet.worlds.AsteroidTerrain.Kind.PALLAS, 256);
        addAsteroid("hygiea", com.thepearlking.stevespace.world.planet.worlds.AsteroidTerrain.Kind.HYGIEA, 217);
    }

    private static void addAsteroid(String id, com.thepearlking.stevespace.world.planet.worlds.AsteroidTerrain.Kind kind, double radius) {
        add(id, new com.thepearlking.stevespace.world.planet.worlds.AsteroidTerrain(kind, radius, 0x417374L * 31 + id.hashCode()),
                com.thepearlking.stevespace.world.gen.worlds.AsteroidColumns::new, 0.1);
    }

    private static void add(String id, BodyTerrain terrain, Supplier<ColumnBuilder> columns, double caves) {
        add(id, terrain, columns, caves, terrain.biomes());
    }

    private static void add(String id, PlanetTerrain terrain, Supplier<ColumnBuilder> columns, double caves,
                            List<? extends SurfaceBiome> biomes) {
        WORLDS.put(id, new Entry(terrain, columns, caves, biomes));
    }

    private PlanetBodies() {
    }

    /** Everything the chunk generator needs for one body, created once the seed is known. */
    public record BodyWorldGen(PlanetTerrain terrain, ColumnBuilder columns, CaveNoise caves,
                               PlanetBiomeSource.CaveBiomes caveBiomes) {
    }

    public static BodyWorldGen create(String body, long worldSeed) {
        Entry e = entry(body);
        long seed = worldSeed ^ (body.hashCode() * 0x9E3779B97F4A7C15L);
        return new BodyWorldGen(e.terrain(), e.columns().get(), new CaveNoise(seed, e.terrain().geometry().circumference(), e.caves()), null);
    }

    /** The terrain of a body, or null if it has no generated surface. */
    public static PlanetTerrain terrain(String body) {
        Entry e = WORLDS.get(body);
        return e == null ? null : e.terrain();
    }

    public static Set<String> bodies() {
        return WORLDS.keySet();
    }

    /** Every biome the body's surface can produce (needed before the seed is known). */
    public static List<? extends SurfaceBiome> surfaceBiomes(String body) {
        return entry(body).biomes();
    }

    /** Sea level of the body, or {@link Integer#MIN_VALUE} if it has no seas. */
    public static int seaLevel(String body) {
        Entry e = WORLDS.get(body);
        return e == null ? Integer.MIN_VALUE : e.terrain().seaLevel();
    }

    public static List<String> caveBiomeIds(String body) {
        return List.of();
    }

    private static Entry entry(String body) {
        Entry e = WORLDS.get(body);
        if (e == null) {
            throw new IllegalArgumentException("Unknown planet body: " + body);
        }
        return e;
    }
}
